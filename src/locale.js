export const LocaleContext = createContext('zh');

export function useTranslation() {
  const language = useContext(LocaleContext);
  return useCallback((key, values = {}) => messages[key][language === 'en' ? 1 : 0]
    .replace(/\{(\w+)\}/g, (_, name) => values[name]), [language]);
}

export function alertMessage(t, row) {
  const kind = row.kind === 'fan' && row.severity === 'info' ? 'fanReminder' : row.kind;
  return t('alert.' + kind, {temperature: row.temperature});
}

export function alertLocation(t, row) {
  if (row.kind === 'pump') return t('loop', {loop: row.location});
  if (row.location === null) return t('locationUnconfirmed');
  return row.location;
}
